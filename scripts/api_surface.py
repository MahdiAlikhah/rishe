"""Print or verify the public API surface of the crate and the Python package.

`python scripts/api_surface.py` rewrites `docs/api-surface.txt`.
`python scripts/api_surface.py --check` fails when the committed file no longer
matches the source, so an accidental rename or removal shows up in review.

Static on purpose: it reads source files only, so it needs no build, no network
and no third-party package. The runtime half (the committed stub matches the
compiled extension) is covered by `python/tests/test_surface.py`.
"""

from __future__ import annotations

import difflib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "docs" / "api-surface.txt"
HEADER = (
    "# Public API surface of rishe. Generated by scripts/api_surface.py; do not edit.\n"
    "# Frozen at 1.0.0: removing or renaming a line needs 2.0.0, adding one is a minor.\n"
)

RUST_ITEM = re.compile(
    r"^\s*pub (?:unsafe )?(?:async )?(fn|struct|enum|trait|const|static|type) (\w+)"
)
RUST_MODULE = re.compile(r"^\s*pub mod (\w+)")
PYTHON_NAME = re.compile(r'"(\w+)"')


def rust_surface() -> list[str]:
    items = []
    for path in sorted((ROOT / "src").glob("*.rs")):
        for line in path.read_text(encoding="utf-8").splitlines():
            match = RUST_ITEM.match(line)
            if match:
                items.append(f"{match.group(1)} {path.stem}::{match.group(2)}")
                continue
            match = RUST_MODULE.match(line)
            if match:
                items.append(f"mod {path.stem}::{match.group(1)}")
    return items


def python_surface() -> list[str]:
    text = (ROOT / "python" / "rishe" / "__init__.py").read_text(encoding="utf-8")
    exported = text.split("__all__", 1)[1].split("]", 1)[0]
    return [f"python {name}" for name in PYTHON_NAME.findall(exported)]


def surface() -> str:
    rust = sorted(set(rust_surface()))
    python = sorted(set(python_surface()))
    out = [HEADER, f"# {len(rust)} Rust items, {len(python)} Python names.\n", "\n[rust]\n"]
    out += [f"{item}\n" for item in rust]
    out += ["\n[python]\n"]
    out += [f"{item}\n" for item in python]
    return "".join(out)


def main(argv: list[str]) -> int:
    expected = surface()
    entries = sum(1 for line in expected.splitlines() if not line.startswith(("#", "[")) and line)
    if "--check" not in argv:
        SNAPSHOT.write_text(expected, encoding="utf-8")
        print(f"wrote docs/api-surface.txt ({entries} entries)")
        return 0
    current = SNAPSHOT.read_text(encoding="utf-8") if SNAPSHOT.exists() else ""
    if current == expected:
        print(f"api surface unchanged ({entries} entries)")
        return 0
    diff = difflib.unified_diff(
        current.splitlines(keepends=True),
        expected.splitlines(keepends=True),
        "docs/api-surface.txt",
        "regenerated",
    )
    sys.stdout.writelines(diff)
    return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
