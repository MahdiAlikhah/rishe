#!/usr/bin/env python3
"""Write, or check, the public API surface snapshot in `docs/api-surface.txt`.

Run with no arguments to regenerate the file. `--check` rebuilds the snapshot in
memory and diffs it against the committed copy: exit 0 when they match, exit 1
and print a unified diff when they drifted.

Rust items come from `pub` declarations in `src/*.rs` (never `src/bin/`), and the
contents of a private `mod` are not public API, so they are skipped. Python names
come from the literal `__all__` in `python/rishe/__init__.py`; the package is
never imported, so no build, wheel or network is needed.
"""
import ast
import difflib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "docs" / "api-surface.txt"
PY_PACKAGE = ROOT / "python" / "rishe" / "__init__.py"

DECL = re.compile(r"pub (fn|struct|enum|trait|type|const|static|union|mod) (\w+)")
IMPL = re.compile(r"^impl\b.*{$")
HEADER = (
    "# Public API surface of rishe. Generated by scripts/api_surface.py; do not edit.",
    "# Frozen at 1.0.0: removing or renaming a line needs 2.0.0, adding one is a minor.",
    "# {rust} Rust items, {python} Python names. Rust: pub items in src/*.rs, src/bin excluded.",
    "# Python: the literal __all__ in python/rishe/__init__.py.",
)


def impl_type(text):
    # `impl<T> Foo<T> where ...` -> Foo; `impl Display for HubError` -> HubError.
    inner = re.sub(r"^<[^>]*>\s*", "", text[4:].rstrip("{").strip())
    return inner.split(" for ")[-1].split("<")[0].split("::")[-1].strip()


def rust_items():
    items = []
    for path in sorted((ROOT / "src").glob("*.rs")):
        module = "lib" if path.name == "lib.rs" else path.stem
        stack = []  # (indent, path, hidden): impl and mod scopes still open
        for line in path.read_text(encoding="utf-8").splitlines():
            text = line.strip()
            if not text or text.startswith(("//", "#[")):
                continue
            indent = len(line) - len(line.lstrip())
            while stack and indent <= stack[-1][0]:
                stack.pop()
            scope, hidden = (stack[-1][1] + "::", stack[-1][2]) if stack else (module + "::", False)
            if text.startswith("pub ") and DECL.match(text):
                kind, name = DECL.match(text).groups()
                if not hidden:
                    items.append(f"{kind} {scope}{name}")
                if kind == "mod":
                    stack.append((indent, scope + name, hidden))
            elif IMPL.match(text):
                stack.append((indent, scope + impl_type(text), hidden))
            elif text.startswith("mod "):
                stack.append((indent, scope + text[4:].split("{")[0].strip(" ;{"), True))
    return items


def python_items():
    for node in ast.parse(PY_PACKAGE.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "__all__" for target in node.targets
        ):
            return [
                entry.value
                for entry in node.value.elts
                if isinstance(entry, ast.Constant) and isinstance(entry.value, str)
            ]
    return []


def snapshot():
    rust, python = sorted(set(rust_items())), sorted(set(python_items()))
    header = [line.format(rust=len(rust), python=len(python)) for line in HEADER]
    lines = header + ["", "[rust]", *rust, "", "[python]", *python, ""]
    return "\n".join(lines)


def main(argv):
    if argv not in ([], ["--check"]):
        print("usage: api_surface.py [--check]", file=sys.stderr)
        return 2
    fresh = snapshot()
    if argv:
        committed = SNAPSHOT.read_text(encoding="utf-8") if SNAPSHOT.exists() else ""
        if committed == fresh:
            print(f"{SNAPSHOT.relative_to(ROOT)}: up to date")
            return 0
        diff = difflib.unified_diff(
            committed.splitlines(True),
            fresh.splitlines(True),
            str(SNAPSHOT.relative_to(ROOT)),
            "regenerated",
        )
        sys.stdout.writelines(diff)
        return 1
    with SNAPSHOT.open("w", encoding="utf-8", newline="\n") as out:
        out.write(fresh)
    print(f"wrote {SNAPSHOT.relative_to(ROOT)} ({len(fresh.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
